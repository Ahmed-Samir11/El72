-- 0003 (timescaledb): first-party app funnel events (plans/p4 MS1).
--
-- Lives in the timescaledb/ migration directory next to the analytical facts it
-- is rolled up with; the operational Postgres database does not have this table.
-- Mirrors the app_events block in infra/sql/schema/timescaledb.sql; idempotent.

-- First-party app funnel events (plans/p4 WS1). Written only by services/api
-- (POST /events); rolled up by services/analyzer. Append-only time series.
--
--   ts          server receipt time; a client clock is never trusted for
--               retention or cohort boundaries.
--   user_id     str(users.id) from the bearer token, never from the request
--               body and never a phone number. NULL for an anonymous session,
--               and set back to NULL when the account is deleted.
--   session_id  install-scoped id generated by the client.
--   event_id    shared with affiliate_clicks.event_id for merchant_click, so the
--               two can be joined without double counting.
--   properties  small, scalar-only context (capped by the API at 20 keys and
--               1 KB serialized). Never free text such as a search query.
CREATE TABLE IF NOT EXISTS app_events (
    id BIGINT GENERATED ALWAYS AS IDENTITY,
    ts TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT NOW(),
    user_id TEXT,
    session_id TEXT NOT NULL,
    event TEXT NOT NULL,
    sku TEXT,
    store_id TEXT,
    category TEXT,
    source TEXT,
    channel TEXT,
    product_id TEXT,
    deal_id TEXT,
    item_id TEXT,
    event_id TEXT,
    properties JSONB,
    -- A hypertable's unique index must include the partitioning column.
    PRIMARY KEY (id, ts),
    CONSTRAINT app_events_event_allowlist CHECK (event IN (
        'search', 'product_view', 'comparison_view', 'track_created',
        'track_removed', 'price_change', 'alert_sent', 'alert_opened',
        'merchant_click', 'purchase', 'limit_hit', 'error_observed'
    ))
);

SELECT create_hypertable('app_events', 'ts')
WHERE NOT EXISTS (
    SELECT 1 FROM timescaledb_information.hypertables
    WHERE hypertable_name = 'app_events'
);

-- Funnel rollups read per day and per event; erasure and retention cohorts read
-- per user.
CREATE INDEX IF NOT EXISTS idx_app_events_event_ts ON app_events (event, ts);
CREATE INDEX IF NOT EXISTS idx_app_events_user_ts ON app_events (user_id, ts);
CREATE INDEX IF NOT EXISTS idx_app_events_session_ts ON app_events (session_id, ts);

-- Retention: events older than the window are dropped chunk by chunk by the
-- TimescaleDB job scheduler, so a funnel trail cannot outlive its purpose.
-- 180 days is the plan's default pending the owner's decision (plans/p4 H9).
-- Third argument: if_not_exists, so re-running this file is a no-op.
SELECT add_retention_policy('app_events', INTERVAL '180 days', true);
